-- Reproducible definition of V91, previously created only in the test database.
ALTER TABLE servamar_test.vessels ADD COLUMN IF NOT EXISTS registration_number text NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS servamar_test.v91_vessel_contacts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vessel_id bigint NOT NULL REFERENCES servamar_test.vessels(id) ON DELETE RESTRICT,
 contact_role text NOT NULL CHECK(contact_role IN ('captain','owner','representative','other')),
 full_name text NOT NULL, email text, phone text,
 is_primary boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL DEFAULT now());
CREATE UNIQUE INDEX IF NOT EXISTS v91_one_primary_contact ON servamar_test.v91_vessel_contacts(vessel_id) WHERE is_primary;
CREATE TABLE IF NOT EXISTS servamar_test.v91_documents (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vessel_id bigint NOT NULL REFERENCES servamar_test.vessels(id) ON DELETE RESTRICT,
 document_type text NOT NULL CHECK(document_type IN ('permiso_ingreso','ampliacion','deposito','salida','retorno','otro')),
 filename text NOT NULL CHECK(length(filename) BETWEEN 1 AND 255),
 mime_type text NOT NULL CHECK(mime_type IN ('application/pdf','image/jpeg','image/png')),
 sha256 text NOT NULL CHECK(sha256 ~ '^[0-9a-f]{64}$'), storage_key text NOT NULL UNIQUE,
 uploaded_at timestamptz NOT NULL DEFAULT now(),
 extracted_fields jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(extracted_fields)='object'),
 verified boolean NOT NULL DEFAULT false);
CREATE TABLE IF NOT EXISTS servamar_test.v91_notification_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vessel_id bigint NOT NULL REFERENCES servamar_test.vessels(id) ON DELETE RESTRICT,
 channel text NOT NULL CHECK(channel IN ('email','push','windows')),
 kind text NOT NULL CHECK(kind IN ('expiry_30','expiry_15','expiry_1','manual')),
 due_date date NOT NULL, status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sent','failed','cancelled')),
 attempt_count integer NOT NULL DEFAULT 0 CHECK(attempt_count>=0),
 last_attempt_at timestamptz, sent_at timestamptz, error_code text, created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(vessel_id,channel,kind,due_date));
